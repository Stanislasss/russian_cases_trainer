// Ending tables per declension pattern ("paradigm"). Language-independent: the
// labels and explanations live in ./texts. Endings are written without a dash;
// "" is the zero ending (стол). Examples carry stress marks.
import type { Schemas } from '../api/client'

export type Case = Schemas['GrammaticalCase']
export type Paradigm = Schemas['DeclensionParadigm']
export type TableParadigm = Exclude<Paradigm, 'personal_pronoun'>
export type Column = 'singular' | 'plural' | 'masculine' | 'neuter' | 'feminine'
export type Group = 'nouns' | 'adjectives' | 'pronouns' | 'surnames'

export const CASES: Case[] = [
  'nominative',
  'genitive',
  'dative',
  'accusative',
  'instrumental',
  'prepositional',
]

export interface Cell {
  /** Every ending of the cell; alternatives follow the spelling rules or the noun's stem. */
  endings: string[]
  /** One or two forms showing them, e.g. "стол, студе́нта". */
  example: string
  /** Masculine/plural accusative: like the nominative (inanimate) or the genitive (animate). */
  animacy?: boolean
}

export interface Table {
  group: Group
  /** Example words heading the table. */
  words: string
  columns: Column[]
  cells: Record<Case, Partial<Record<Column, Cell>>>
}

/** [endings, example]; endings "ы/и", "∅" for none, a leading "~" for animacy-dependent. */
type Spec = [endings: string, example: string]

/** Builds a table from rows of specs per column, in case order. */
function table(group: Group, words: string, columns: Column[], rows: Spec[][]): Table {
  const cells = {} as Table['cells']
  CASES.forEach((c, i) => {
    cells[c] = {}
    columns.forEach((column, j) => {
      const [spec, example] = rows[i][j]
      const animacy = spec.startsWith('~')
      cells[c][column] = {
        endings: spec
          .replace('~', '')
          .split('/')
          .map((e) => (e === '∅' ? '' : e)),
        example,
        ...(animacy && { animacy }),
      }
    })
  })
  return { group, words, columns, cells }
}

